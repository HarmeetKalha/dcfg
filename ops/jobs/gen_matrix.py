"""Generate configs/train/<run_id>.yaml for the PLAN 7.4 Tier 1-2 runs and PRINT their queue lines.

    .venv/bin/python ops/jobs/gen_matrix.py [--out-dir configs/train] [--batch-yaml results/qa/phase8_batch.yaml]
    .venv/bin/python ops/jobs/gen_matrix.py --no-write            # only print the queue lines

Never touches ops/queue.txt: the user decides what to append. Order (PLAN 8.4): Tier 1 Xception
(dcfg, fixed, augft), EfficientNet-B4, F3Net, UCF, then Tier 2. Per run: a train job (heartbeat from
the trainer in runs/<run_id>) followed by ``eval_<run_id>``, the test evaluation over all conditions.
Batch sizes per detector come from ``results/qa/phase8_batch.yaml`` (written by phase8_smoke.py,
``{detector: batch}``); missing file or detector -> 32 with a warning on stderr.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Any

import yaml

REPO = Path(__file__).resolve().parents[2]
PY = ".venv/bin/python"
DETECTORS = ["xception", "efficientnetb4", "f3net", "ucf"]
TIER1_VARIANTS = ["dcfg", "fixed", "augft"]
DEFAULT_BATCH = 32
#: Tier 2 (all Xception, seed 42 unless suffixed): (run_id, variant, seed, freeze_sensor)
TIER2: list[tuple[str, str, int, bool]] = [
    ("dcfg_jointft_xception", "dcfg_jointft", 42, False),
    ("dcfg_nolive_xception", "dcfg_nolive", 42, False),
    ("gate_nosensor_xception", "nosensor", 42, False),
    ("dcfg_frozensensor_xception", "dcfg", 42, True),
    ("dcfg_xception_s43", "dcfg", 43, False),
    ("dcfg_xception_s44", "dcfg", 44, False),
    ("fixed_xception_s43", "fixed", 43, False),
    ("fixed_xception_s44", "fixed", 44, False),
]


def matrix_runs() -> list[dict[str, Any]]:
    """The Tier 1-2 runs in PLAN 8.4 order: dicts with run_id, tier, variant, detector, seed, freeze_sensor."""
    runs: list[dict[str, Any]] = []
    for det in DETECTORS:
        for v in TIER1_VARIANTS:
            runs.append({"run_id": f"{v}_{det}", "tier": 1, "variant": v, "detector": det, "seed": 42,
                         "freeze_sensor": False})
    for rid, v, seed, fz in TIER2:
        runs.append({"run_id": rid, "tier": 2, "variant": v, "detector": "xception", "seed": seed,
                     "freeze_sensor": fz})
    return runs


def load_batch(path: Path) -> dict[str, int]:
    """``{detector: batch_size}``; empty dict (with a warning) if the file is missing."""
    if not path.exists():
        print(f"WARNING: {path} missing; using batch_size {DEFAULT_BATCH} for all detectors", file=sys.stderr)
        return {}
    return {str(k): int(v) for k, v in (yaml.safe_load(path.read_text()) or {}).items()}


def config_text(run: dict[str, Any], batch: int) -> str:
    """Yaml for one run (merged over base.yaml by train_frontend.load_config)."""
    lines = ["# generated by ops/jobs/gen_matrix.py (PLAN 7.4); do not edit by hand",
             "base: base.yaml", f"run_id: {run['run_id']}", f"variant: {run['variant']}",
             f"detector: {run['detector']}", f"seed: {run['seed']}", f"batch_size: {batch}"]
    if run["freeze_sensor"]:
        lines.append("freeze_sensor: true")
    return "\n".join(lines) + "\n"


def queue_lines(run: dict[str, Any]) -> list[str]:
    """Train job, then its test-evaluation job (all conditions) with the trained artefacts."""
    rid, det = run["run_id"], run["detector"]
    ev = f"{PY} -m dcfg.eval.evaluate --run {rid} --detector {det} --conditions all --split test"
    if run["variant"] != "augft":
        ev += f" --frontend runs/{rid}/frontend.pt"
    if run["variant"] in ("augft", "dcfg_jointft"):
        ev += f" --detector-ckpt runs/{rid}/detector.pt"
    return [f"{rid} | {PY} -m dcfg.train.train_frontend --config configs/train/{rid}.yaml #hb=30",
            f"eval_{rid} | {ev} #hb=30"]


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--out-dir", default=str(REPO / "configs/train"))
    ap.add_argument("--batch-yaml", default=str(REPO / "results/qa/phase8_batch.yaml"))
    ap.add_argument("--no-write", action="store_true")
    a = ap.parse_args(argv)
    batch = load_batch(Path(a.batch_yaml))
    out = Path(a.out_dir)
    for run in matrix_runs():
        if not a.no_write:
            out.mkdir(parents=True, exist_ok=True)
            (out / f"{run['run_id']}.yaml").write_text(config_text(run, batch.get(run["detector"], DEFAULT_BATCH)))
        print("\n".join(queue_lines(run)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
