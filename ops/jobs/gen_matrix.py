"""Generate configs/train/<run_id>.yaml for the LUMEN matrix and PRINT its queue lines.

    .venv/bin/python ops/jobs/gen_matrix.py [--out-dir configs/train] [--batch-yaml results/qa/phase8_batch.yaml]
    .venv/bin/python ops/jobs/gen_matrix.py --no-write            # only print the queue lines
    .venv/bin/python ops/jobs/gen_matrix.py --queue-out results/qa/lumen_queue.txt   # also write the lines

Never touches ops/queue.txt: the user decides what to append. Groups (user decision, final method LUMEN):
G1 core (lumen/fixed/augft x 4 detectors), G2 (jointft_xception, bnft_xception), G3 Xception ablation chain
(dcfg, dcfgcons, lumen_nocons, lumen_nolive, lumen_frozensensor), G4 seeds (lumen/augft Xception s43, s44).
Each run = a train job immediately followed by its own test-eval job (``--conditions all --split test``); each
queue line is independent. After the last eval of a group: ``findings_group<N>`` (ops/jobs/group_findings.py).
Base results (base_<det>) already exist and are not regenerated. Real configs: pilot false, timing_sync false,
stop_after_epochs unset (all from base.yaml), 30 epochs, patience 6, seed per run, batch from phase8_batch.yaml.
Stale configs generated by the OLD matrix (header "generated by ops/jobs/gen_matrix.py") are removed by
``--prune`` (listed; hand-written configs and pilot/ are never touched).
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Any

import yaml

REPO = Path(__file__).resolve().parents[2]
PY = ".venv/bin/python"
DETECTORS = ["xception", "efficientnetb4", "f3net", "ucf"]
DEFAULT_BATCH = 32
HEADER = "# generated by ops/jobs/gen_matrix.py (LUMEN matrix); do not edit by hand"
OLD_HEADER_MARK = "generated by ops/jobs/gen_matrix.py"
#: (run_id, variant, detector, seed)
GROUPS: dict[int, list[tuple[str, str, str, int]]] = {
    1: [(f"{v}_{d}", var, d, 42) for d in DETECTORS for v, var in (("lumen", "lumen"), ("fixed", "fixed"), ("augft", "augft"))],
    2: [("jointft_xception", "dcfg_jointft", "xception", 42), ("bnft_xception", "bnft", "xception", 42)],
    3: [("dcfg_xception", "dcfg", "xception", 42), ("dcfgcons_xception", "dcfg_cons", "xception", 42),
        ("lumen_nocons_xception", "lumen_nocons", "xception", 42), ("lumen_nolive_xception", "lumen_nolive", "xception", 42),
        ("lumen_frozensensor_xception", "lumen_frozensensor", "xception", 42)],
    4: [("lumen_xception_s43", "lumen", "xception", 43), ("lumen_xception_s44", "lumen", "xception", 44),
        ("augft_xception_s43", "augft", "xception", 43), ("augft_xception_s44", "augft", "xception", 44)],
}


def matrix_runs() -> list[dict[str, Any]]:
    """All runs in queue order: dicts with run_id, group (1-4), variant, detector, seed, freeze_sensor."""
    return [{"run_id": rid, "group": g, "tier": 1 if g == 1 else 2, "variant": var, "detector": det, "seed": seed,
             "freeze_sensor": var == "lumen_frozensensor"}
            for g, entries in GROUPS.items() for rid, var, det, seed in entries]


def load_batch(path: Path) -> dict[str, int]:
    """``{detector: batch_size}``; empty dict (with a warning) if the file is missing."""
    if not path.exists():
        print(f"WARNING: {path} missing; using batch_size {DEFAULT_BATCH} for all detectors", file=sys.stderr)
        return {}
    return {str(k): int(v) for k, v in (yaml.safe_load(path.read_text()) or {}).items()}


#: bnft (BN-only tuning) default lr; user decision 2026-11-19 (DECISIONS.md): at the full-fine-tune lr 2e-5 the
#: 55.6k BN affine params would be undertrained, so bnft uses the LUMEN gate lr.
BNFT_LR = "1.0e-3"
BNFT_LR_COMMENT = "# bnft: BN-only tuning at lr_detector 1e-3 (user decision 2026-11-19, see DECISIONS.md)"


def config_text(run: dict[str, Any], batch: int) -> str:
    """Yaml for one run (merged over base.yaml by train_frontend.load_config)."""
    lines = [HEADER, "base: base.yaml", f"run_id: {run['run_id']}", f"variant: {run['variant']}",
             f"detector: {run['detector']}", f"seed: {run['seed']}", f"batch_size: {batch}"]
    if run["freeze_sensor"]:
        lines.append("freeze_sensor: true")
    if run["variant"] == "bnft":
        lines += [BNFT_LR_COMMENT, f"lr_detector: {BNFT_LR}"]
    return "\n".join(lines) + "\n"


def queue_lines(run: dict[str, Any]) -> list[str]:
    """Train job, then its test-evaluation job (all conditions) with the trained artefacts."""
    rid, det, var = run["run_id"], run["detector"], run["variant"]
    ev = f"{PY} -m dcfg.eval.evaluate --run {rid} --detector {det} --conditions all --split test"
    if var == "bnft":
        ev += f" --bn-ckpt runs/{rid}/bn.pt"
    elif var != "augft":
        ev += f" --frontend runs/{rid}/frontend.pt"
    if var in ("augft", "dcfg_jointft"):
        ev += f" --detector-ckpt runs/{rid}/detector.pt"
    return [f"{rid} | {PY} -m dcfg.train.train_frontend --config configs/train/{rid}.yaml #hb=30",
            f"eval_{rid} | {ev} #hb=30"]


def findings_line(group: int) -> str:
    return f"findings_group{group} | {PY} ops/jobs/group_findings.py --group {group} #noheartbeat"


def all_queue_lines() -> list[str]:
    """Every queue line in order, a findings line after each group's last eval."""
    out: list[str] = []
    runs = matrix_runs()
    for g in GROUPS:
        for r in (x for x in runs if x["group"] == g):
            out += queue_lines(r)
        out.append(findings_line(g))
    return out


def stale_configs(out: Path) -> list[Path]:
    """Top-level configs in ``out`` written by gen_matrix (header mark) whose run_id is not in the matrix."""
    keep = {r["run_id"] for r in matrix_runs()}
    return sorted(p for p in out.glob("*.yaml")
                  if p.stem not in keep and OLD_HEADER_MARK in p.read_text().splitlines()[0])


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--out-dir", default=str(REPO / "configs/train"))
    ap.add_argument("--batch-yaml", default=str(REPO / "results/qa/phase8_batch.yaml"))
    ap.add_argument("--no-write", action="store_true")
    ap.add_argument("--prune", action="store_true", help="delete stale gen_matrix-generated configs (listed)")
    ap.add_argument("--queue-out", default=None, help="also write the queue lines to this file")
    a = ap.parse_args(argv)
    batch = load_batch(Path(a.batch_yaml))
    out = Path(a.out_dir)
    if a.prune:
        for p in stale_configs(out):
            print(f"removing stale config {p.name}", file=sys.stderr)
            p.unlink()
    if not a.no_write:
        out.mkdir(parents=True, exist_ok=True)
        for run in matrix_runs():
            (out / f"{run['run_id']}.yaml").write_text(config_text(run, batch.get(run["detector"], DEFAULT_BATCH)))
    lines = all_queue_lines()
    print("\n".join(lines))
    if a.queue_out:
        Path(a.queue_out).parent.mkdir(parents=True, exist_ok=True)
        Path(a.queue_out).write_text("\n".join(lines) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
